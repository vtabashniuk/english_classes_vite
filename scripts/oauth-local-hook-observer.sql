-- Local-only diagnostic SQL. Never add this file to supabase/migrations.
-- Install only through scripts/oauth-local-hook-observer.mjs with local Docker guard.
BEGIN;
CREATE SCHEMA IF NOT EXISTS oauth_probe;
REVOKE ALL ON SCHEMA oauth_probe FROM PUBLIC;

CREATE TABLE IF NOT EXISTS oauth_probe.created_user_hook_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid,
  observed_at timestamptz NOT NULL DEFAULT now(),
  app_provider text,
  untrusted_role text,
  has_invited_at boolean NOT NULL,
  has_email_confirmed_at boolean NOT NULL,
  user_field_names text[] NOT NULL,
  metadata_field_names text[] NOT NULL
);
REVOKE ALL ON oauth_probe.created_user_hook_events FROM PUBLIC, anon, authenticated;

CREATE OR REPLACE FUNCTION oauth_probe.before_user_created_observe(event jsonb)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $body$
BEGIN
  -- Never persist email, IP address, JWT, raw metadata or provider tokens.
  INSERT INTO oauth_probe.created_user_hook_events (
    user_id, app_provider, untrusted_role,
    has_invited_at, has_email_confirmed_at,
    user_field_names, metadata_field_names
  ) VALUES (
    nullif(event->'user'->>'id', '')::uuid,
    event->'user'->'app_metadata'->>'provider',
    event->'user'->'user_metadata'->>'role',
    (event->'user' ? 'invited_at') AND (event->'user'->>'invited_at' IS NOT NULL),
    (event->'user' ? 'email_confirmed_at') AND (event->'user'->>'email_confirmed_at' IS NOT NULL),
    ARRAY(SELECT k FROM jsonb_object_keys(coalesce(event->'user', '{}'::jsonb)) AS t(k) ORDER BY k),
    ARRAY(SELECT k FROM jsonb_object_keys(coalesce(event->'metadata', '{}'::jsonb)) AS t(k) ORDER BY k)
  );
  -- This diagnostic hook MUST NOT make authorization decisions.
  RETURN '{}'::jsonb;
END;
$body$;
REVOKE ALL ON FUNCTION oauth_probe.before_user_created_observe(jsonb) FROM PUBLIC, anon, authenticated;
GRANT USAGE ON SCHEMA oauth_probe TO supabase_auth_admin;
GRANT EXECUTE ON FUNCTION oauth_probe.before_user_created_observe(jsonb) TO supabase_auth_admin;
COMMIT;
